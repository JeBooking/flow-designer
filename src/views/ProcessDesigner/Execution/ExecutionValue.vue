<script setup lang="ts">
const props = withDefaults(defineProps<{ value: unknown; depth?: number }>(), { depth: 0 })
const isObject = (value: unknown): value is Record<string, unknown> =>
  value !== null && typeof value === 'object' && !Array.isArray(value)
const entries = computed(() =>
  isObject(props.value)
    ? Object.entries(props.value).filter(([key]) => key !== 'chartSvg' || !chart.value)
    : [],
)
const chart = computed(() => {
  const svg = isObject(props.value) ? props.value.chartSvg : undefined
  return typeof svg === 'string' && svg.trim()
    ? `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`
    : ''
})
const rows = computed(() => (Array.isArray(props.value) ? props.value.slice(0, 30) : []))
const allColumns = computed(() => [
  ...new Set(rows.value.flatMap((row) => (isObject(row) ? Object.keys(row) : []))),
])
const columns = computed(() => allColumns.value.slice(0, 8))
const objectRows = computed(() => rows.value.length > 0 && rows.value.every(isObject))
const scalar = (value: unknown) =>
  value === null ? 'null' : value === undefined ? '—' : String(value)
const nested = (value: unknown) => value !== null && typeof value === 'object'
</script>

<template>
  <div class="execution-value">
    <img
      v-if="chart"
      :src="chart"
      :alt="$tu('Python 生成的诊断图表', 'Diagnostic chart generated by Python')"
    />
    <template v-if="depth < 3 && nested(value)">
      <template v-if="Array.isArray(value)">
        <p v-if="!value.length">{{ $tu('空列表', 'Empty list') }}</p>
        <div v-else-if="objectRows" class="table-scroll">
          <table>
            <thead>
              <tr>
                <th v-for="column in columns" :key="column" scope="col">{{ column }}</th>
              </tr>
            </thead>
            <tbody>
              <tr v-for="(row, index) in rows" :key="index">
                <td v-for="column in columns" :key="column">
                  <ExecutionValue
                    :value="(row as Record<string, unknown>)[column]"
                    :depth="depth + 1"
                  />
                </td>
              </tr>
            </tbody>
          </table>
        </div>
        <ol v-else>
          <li v-for="(row, index) in rows" :key="index">
            <ExecutionValue :value="row" :depth="depth + 1" />
          </li>
        </ol>
        <p v-if="value.length > 30 || (objectRows && allColumns.length > 8)" class="muted">
          {{
            $tu(
              '仅显示前 30 行、8 列；完整内容见原始详情。',
              'Showing up to 30 rows and 8 columns; see raw details for the complete value.',
            )
          }}
        </p>
      </template>
      <dl v-else-if="entries.length">
        <template v-for="[key, entry] in entries" :key="key">
          <dt>{{ key }}</dt>
          <dd>
            <details v-if="nested(entry)">
              <summary>{{ $tu('展开内容', 'Expand value') }}</summary>
              <ExecutionValue :value="entry" :depth="depth + 1" />
            </details>
            <template v-else>{{ scalar(entry) }}</template>
          </dd>
        </template>
      </dl>
      <span v-else-if="!chart">{{ $tu('空对象', 'Empty object') }}</span>
    </template>
    <details v-else-if="nested(value)">
      <summary>{{ $tu('查看嵌套数据', 'View nested data') }}</summary>
      <pre>{{ JSON.stringify(value, null, 2) }}</pre>
    </details>
    <span v-else>{{ scalar(value) }}</span>
  </div>
</template>

